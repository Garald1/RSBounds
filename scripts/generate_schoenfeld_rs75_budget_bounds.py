"""Generate RSBounds/SchoenfeldRS75BudgetBounds.lean: an upper bound for the high-zero weight K
(`QuarticFirst29BudgetNumerics.highWeight`) of the RS75 b = 23 chain, as a kernel-checked
interval certificate.

The upper bound for the critical-line coefficient Q (`sqrtCoefficient`) needs no new certificate:
the Lean file reuses the public `coefficientCertificate` of QuarticFirst29BudgetNumerics.

The interval arithmetic below copies scripts/generate_quartic_budget_certificate.py (same
logarithm certificates, same node format). Python is not trusted: Lean checks every node with
`decide +kernel` and proves that the expression evaluates to `highWeight` with `norm_num`.
No existing file is modified.
"""
from fractions import Fraction as Q
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent.parent
D = 10 ** 30
ARG_SCALE = 10 ** 12
nodes = []
cache = {}


def qtext(q):
    q = Q(q)
    return str(q.numerator) if q.denominator == 1 else f"{q.numerator}/{q.denominator}"


def qbounds(a, b):
    lo = sum(2 * D * b ** (2*j+1) // ((2*j+1) * (2*a+b) ** (2*j+1))
             for j in range(12))
    hi = lo + 12 + 3 * D * b ** 25 // (25 * (2*a+b) ** 25) + 1
    return Q(lo, D), Q(hi, D)


def logcert(q):
    q = Q(q)
    assert q > 1
    k = 0
    while q > 2:
        q /= 2
        k += 1
    a, b = q.denominator, q.numerator-q.denominator
    assert 0 < b <= a
    lo, hi = qbounds(a, b)
    lo2, hi2 = qbounds(1, 1)
    return (k, a, b), k * lo2 + lo, k * hi2 + hi


def make(op, *args):
    key = (op, *args)
    if key in cache:
        return cache[key]
    certs = None
    if op == 'rat':
        lo = hi = Q(args[0])
    elif op == 'pi':
        lo, hi = Q('3.14159265358979323846'), Q('3.14159265358979323847')
    elif op in ('add', 'sub', 'mul'):
        a, b = [nodes[i] for i in args]
        if op == 'add':
            lo, hi = a['lo'] + b['lo'], a['hi'] + b['hi']
        elif op == 'sub':
            lo, hi = a['lo'] - b['hi'], a['hi'] - b['lo']
        else:
            products = [x*y for x in [a['lo'], a['hi']] for y in [b['lo'], b['hi']]]
            lo, hi = min(products), max(products)
    elif op == 'inv':
        a = nodes[args[0]]
        assert a['lo'] > 0
        lo, hi = 1 / a['hi'], 1 / a['lo']
    elif op == 'pow':
        a, n = nodes[args[0]], args[1]
        lo = hi = Q(1)
        for _ in range(n):
            products = [x*y for x in [lo, hi] for y in [a['lo'], a['hi']]]
            lo, hi = min(products), max(products)
    elif op == 'log':
        a = nodes[args[0]]
        low_arg = Q(a['lo'] * ARG_SCALE // 1, ARG_SCALE)
        upper_arg = Q(-((-a['hi'] * ARG_SCALE) // 1), ARG_SCALE)
        cl, lo, _ = logcert(low_arg)
        cu, _, hi = logcert(upper_arg)
        certs = cl, cu
        assert low_arg <= a['lo'] and a['hi'] <= upper_arg
    else:
        raise ValueError(op)
    i = len(nodes)
    nodes.append(dict(op=op, args=args, lo=lo, hi=hi, certs=certs))
    cache[key] = i
    return i


def rat(q): return make('rat', Q(q))
def add(a, b): return make('add', a, b)
def mul(a, b): return make('mul', a, b)
def div(a, b): return mul(a, make('inv', b))
def power(a, n): return make('pow', a, n)
def log(a): return make('log', a)


delta = Q(211, 10**7)
C = ((1+delta)**5 + 1)**4 / delta**4
A = Q(9472192561, 5000)  # = 1894438.5122
pi = make('pi')
twopi = mul(rat(2), pi)


def R(t):
    return add(add(mul(rat(Q(137, 1000)), log(t)),
                   mul(rat(Q(443, 1000)), log(log(t)))), rat(Q(397, 250)))


def J(t):
    first = div(add(div(log(div(t, twopi)), rat(4)), rat(Q(1, 16))),
                mul(twopi, power(t, 4)))
    second = div(rat(Q(137, 1000)), mul(rat(5), power(t, 5)))
    third = div(rat(Q(443, 1000)), mul(mul(rat(5), power(t, 5)), log(t)))
    return add(add(first, second), third)


h = rat(A)
K = mul(rat(C), add(J(h), div(mul(rat(2), R(h)), power(h, 5))))
K_HI = Q(321, 10**8)
assert nodes[K]['lo'] > 0
assert nodes[K]['hi'] < K_HI

header = '''import RSBounds.QuarticFirst29BudgetApplication

/-!
# Upper bounds for the two constants of the RS75 `b = 23` budget

Generated by scripts/generate_schoenfeld_rs75_budget_bounds.py.

The RS75 `b = 23` chain (`RosserSchoenfeld1975`) bounds `|ψ(x) − x| / x`, for every
`x ≥ e^23`, by `QuarticFirst29BudgetApplication.relativeBudget x`
`= 2δ + K + Q/√x + (K + log 2π + 0.1)/x` with `δ = 0.0000211`, `K = highWeight` and
`Q = sqrtCoefficient`. The file `QuarticFirst29BudgetNumerics` certifies the whole budget only at
`√x = 98715`. Larger `x` need `K` and `Q` separately:

* `highWeight_lt : highWeight < 3.21 · 10⁻⁶` (new interval certificate below);
* `sqrtCoefficient_lt : sqrtCoefficient < 15.47` (the existing public `coefficientCertificate`).

Only scalar arithmetic is certified here; every logarithm enclosure and rational comparison is
checked by Lean's kernel.
-/

namespace TernaryGoldbach.RSBounds.SchoenfeldRS75BudgetBounds
open QuarticBudgetNumerics QuarticFirst29BudgetNumerics

set_option maxRecDepth 100000
set_option maxHeartbeats 0

/-! The literal expression certificate for `highWeight`. LogCert parameters do not enter eval. -/
'''
lines = [header]
def certtext(c): return '⟨' + ', '.join(map(str, c)) + '⟩'
for i, n in enumerate(nodes):
    op, args = n['op'], n['args']
    if op == 'rat': rhs = f'.rat ({qtext(args[0])})'
    elif op == 'pi': rhs = '.pi'
    elif op in ('add', 'sub', 'mul'): rhs = f'.{op} n{args[0]} n{args[1]}'
    elif op == 'inv': rhs = f'.inv n{args[0]}'
    elif op == 'pow': rhs = f'.pow n{args[0]} {args[1]}'
    elif op == 'log': rhs = f'.log {certtext(n["certs"][0])} {certtext(n["certs"][1])} n{args[0]}'
    lines.append(f'private def n{i} : Expr := {rhs}')
all_names = ', '.join(f'n{i}' for i in range(len(nodes)))
lines.append(f'''

def highWeightCertificate : Expr := n{K}

theorem highWeightCertificate_checked : highWeightCertificate.check = true := by
  decide +kernel

theorem highWeightCertificate_upper :
    highWeightCertificate.bounds.hi < ({qtext(K_HI)} : ℚ) := by
  decide +kernel

theorem highWeightCertificate_eval : highWeightCertificate.eval = highWeight := by
  norm_num [highWeightCertificate, Expr.eval, {all_names}, highWeight, fifthTail, R, C, A, delta,
    div_eq_mul_inv]

/-- The high-zero weight `K` of the RS75 `b = 23` budget. -/
theorem highWeight_lt : highWeight < 3.21e-6 := by
  rw [← highWeightCertificate_eval]
  convert Expr.eval_lt highWeightCertificate_checked highWeightCertificate_upper using 1 <;> norm_num

theorem coefficientCertificate_upper :
    coefficientCertificate.bounds.hi < (1547 / 100 : ℚ) := by
  decide +kernel

/-- The critical-line coefficient `Q` of the RS75 `b = 23` budget. -/
theorem sqrtCoefficient_lt : sqrtCoefficient < 15.47 := by
  rw [← coefficientCertificate_eval]
  convert Expr.eval_lt coefficientCertificate_checked coefficientCertificate_upper using 1 <;> norm_num

end TernaryGoldbach.RSBounds.SchoenfeldRS75BudgetBounds
''')
(ROOT / 'RSBounds/SchoenfeldRS75BudgetBounds.lean').write_text('\n'.join(lines))
record = {'status': 'generated; Lean kernel verification required', 'nodes': len(nodes),
          'log_nodes': sum(n['op'] == 'log' for n in nodes),
          'highWeight_lower_diagnostic': float(nodes[K]['lo']),
          'highWeight_upper_diagnostic': float(nodes[K]['hi']),
          'highWeight_claimed_bound': qtext(K_HI)}
(ROOT / 'verification/schoenfeld-rs75-budget-bounds-generated.json').write_text(
    json.dumps(record, indent=2) + '\n')
print(record)
