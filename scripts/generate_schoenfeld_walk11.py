"""Generate RSBounds/SchoenfeldWalk11Data.lean: the walk below 1500 for Schoenfeld (1976),
Theorem 11 ((7.2) from 17, (7.3) from 101, (7.4) from 1), in blocks with explicit lower bounds
for eps0 (see RSBounds/SchoenfeldWalk11.lean). Lean's kernel rechecks every walk segment and every
inequality between integers below; Python only chooses the blocks and witnesses.
Usage: python3 -I scripts/generate_schoenfeld_walk11.py
"""
import sys, math
from fractions import Fraction as F
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_schoenfeld_prime_walk as g

ROOT = g.ROOT
D, HUGE = g.D, g.HUGE
K_N, K_D = 9645908801, 10 ** 9
END = 1500
SC = 10 ** 6


def lo(m): return g.logLo(m)
def hi(m): return g.logHi(m)


def witnesses(an, ad, bn, bd):
    """(sn, sd, un, ud, wn, wd) passing the integer checks of `epsOk`."""
    sd = ud = wd = SC
    la = (lo(an) - hi(ad)) / D
    sn = int((la * K_D / K_N) ** 0.25 * SC)
    while not (K_N * sn ** 4 * D + K_D * sd ** 4 * hi(ad) <= K_D * sd ** 4 * lo(an)):
        sn -= 1
    lb = (hi(bn) - lo(bd)) / D
    un = int(math.sqrt(lb * K_D / K_N) * SC) + 1
    while not (K_D * ud ** 2 * hi(bn) <= K_N * un ** 2 * D + K_D * ud ** 2 * lo(bd)):
        un += 1
    wn = int(math.exp(-un / ud) * SC)
    while not (ud * hi(wn) + un * D <= ud * lo(wd)):
        wn -= 1
    assert wn >= 2 and sn > 0
    return sn, sd, un, ud, wn, wd


def E_of(w):
    sn, sd, un, ud, wn, wd = w
    return F(387 * sn * wn, 1000 * sd * wd)


def thr(a, w):
    """floor(D a E), the largest t with thrOk (2a) 2 t."""
    sn, sd, un, ud, wn, wd = w
    return (D * 2 * a * 387 * sn * wn) // (1000 * sd * wd * 2)


def need(n, st):
    Tlo, Thi, Plo, Phi = st
    return (Thi - D * n + 1, D * (n + 1) - Tlo, Phi - D * n + 1, D * (n + 1) - Plo)


def plan(T):
    segs = [(1, 17, (HUGE, HUGE, 0, HUGE), None)]
    for n in range(1, 17):
        assert need(n, T[n])[2] <= 0
    a = 17
    while a < END:
        if a == 22:
            segs.append((22, 23, (HUGE, HUGE, HUGE, HUGE), None))
            a = 23
            continue
        best = None
        for b in range(a + 1, END + 1):
            if a < 22 < b or a < 101 < b:
                break
            w = witnesses(2 * a, 2, 2 * b, 2)
            t = thr(a, w)
            ok = True
            for n in range(a, b):
                nd = need(n, T[n])
                if nd[2] > t or nd[3] > t:
                    ok = False
                if a >= 101 and (nd[0] > t or nd[1] > t):
                    ok = False
                if not ok:
                    break
            if not ok:
                break
            best = (b, w, t)
        assert best, a
        b, w, t = best
        r = (t, t, t, t) if a >= 101 else (HUGE, HUGE, t, t)
        segs.append((a, b, r, w))
        a = b
    return segs


SUBS = [((44, 2), (45, 2)), ((45, 2), (229, 10)), ((229, 10), (46, 2))]


def sub_checks(st, an, ad, bn, bd, w):
    Tlo, Thi, Plo, Phi = st
    sn, sd, un, ud, wn, wd = w
    hu = Phi * ad * (1000 * sd * wd) < D * an * (1000 * sd * wd + 387 * sn * wn)
    hl = bn * ad * (1000 * sd * wd) * D <= bd * (Plo * ad * (1000 * sd * wd) + D * an * (387 * sn * wn))
    return hu and hl


def lit(st): return '⟨' + ', '.join(map(str, st)) + '⟩'
def wl(w): return ' '.join(f'(sn := {w[0]}) (sd := {w[1]}) (un := {w[2]}) (ud := {w[3]}) (wn := {w[4]}) (wd := {w[5]})'.split(' '))


def main():
    T = g.run()
    segs = plan(T)
    subw = []
    for (an, ad), (bn, bd) in SUBS:
        w = witnesses(an, ad, bn, bd)
        assert sub_checks(T[22], an, ad, bn, bd, w), (an, ad)
        subw.append(w)
    print(len(segs), "segments:", [(a, b) for a, b, _, _ in segs])
    for a, b, r, w in segs:
        if w:
            print(a, b, float(E_of(w)))
    out = ["import RSBounds.SchoenfeldWalk11", "",
           "/-! Generated by `scripts/generate_schoenfeld_walk11.py`: the walk below 1500 in the blocks of",
           "Theorem 11, every segment and every integer inequality rechecked by the kernel. -/", "",
           "open Real", "",
           "namespace TernaryGoldbach.RSBounds.SchoenfeldPrimeWalk", "",
           "set_option maxRecDepth 100000", "set_option linter.unnecessarySeqFocus false", "",
           "local notation \"ε₀\" => Goals.Schoenfeld1976.epsilon0", ""]
    prev_inv = "Inv_one"
    for a, b, r, w in segs:
        R = f"⟨{r[0]}, {r[1]}, {r[2]}, {r[3]}⟩"
        out.append(f"theorem w11_{a} : SegH {a} {b} {R} {lit(T[a])} {lit(T[b])} :=\n"
                   f"  segH_of (L := {b - a}) {R} (by norm_num) (by norm_num) (by decide +kernel)\n")
        out.append(f"theorem h11_{a} : ∀ n, {a} ≤ n → n < {b} → Holds n {R} := (w11_{a} {prev_inv}).2\n")
        out.append(f"theorem i11_{b} : Inv {b} {lit(T[b])} := (w11_{a} {prev_inv}).1\n")
        prev_inv = f"i11_{b}"
    psi_blocks, theta_blocks = [], []
    for a, b, r, w in segs:
        if w is None:
            continue
        out.append(f"theorem psi11_{a} : ∀ x : ℝ, (({a} : ℕ) : ℝ) ≤ x → x < (({b} : ℕ) : ℝ) →\n"
                   f"    |Chebyshev.psi x - x| < x * ε₀ x :=\n"
                   f"  block_psi h11_{a} {wl(w)}\n    (by decide +kernel) (by decide +kernel) (by decide +kernel)\n")
        psi_blocks.append((F(a), F(b), f"psi11_{a}"))
        if a >= 101:
            out.append(f"theorem theta11_{a} : ∀ x : ℝ, (({a} : ℕ) : ℝ) ≤ x → x < (({b} : ℕ) : ℝ) →\n"
                       f"    |Chebyshev.theta x - x| < x * ε₀ x :=\n"
                       f"  block_theta h11_{a} {wl(w)}\n    (by decide +kernel) (by decide +kernel) (by decide +kernel)\n")
            theta_blocks.append((F(a), F(b), f"theta11_{a}"))
    for i, (((an, ad), (bn, bd)), w) in enumerate(zip(SUBS, subw)):
        out.append(f"theorem psi11_22_{i} : ∀ x : ℝ, (({an} : ℕ) : ℝ) / (({ad} : ℕ) : ℝ) ≤ x →\n"
                   f"    x < (({bn} : ℕ) : ℝ) / (({bd} : ℕ) : ℝ) → |Chebyshev.psi x - x| < x * ε₀ x :=\n"
                   f"  sub_psi i11_22 {wl(w)} (an := {an}) (ad := {ad}) (bn := {bn}) (bd := {bd})\n"
                   f"    (by decide +kernel) (by norm_num) (by norm_num) (by decide +kernel) (by decide +kernel)\n")
        psi_blocks.append((F(an, ad), F(bn, bd), f"psi11_22_{i}"))
    psi_blocks.sort()

    def cases(blocks, lo_, concl):
        lines = []
        for i, (a, b, name) in enumerate(blocks):
            bl = f"({b.numerator} : ℝ) / {b.denominator}"
            if i < len(blocks) - 1:
                lines.append(f"  rcases lt_or_ge x ({bl}) with c{i} | c{i}")
                lines.append(f"  · exact {name} x (by norm_num <;> linarith) (by norm_num <;> linarith)")
            else:
                lines.append(f"  exact {name} x (by norm_num <;> linarith) (by norm_num <;> linarith)")
        return lines

    out.append("/-- Theorem 11, (7.4), on `[1, 17)`. -/")
    out.append("theorem small_psi_upper {x : ℝ} (h1 : 1 ≤ x) (h2 : x < 17) :\n"
               "    Chebyshev.psi x - x < x * ε₀ x := by\n"
               "  have hx0 : 0 ≤ x := by linarith\n"
               "  have hn1 : 1 ≤ ⌊x⌋₊ := Nat.le_floor (by exact_mod_cast h1)\n"
               "  have hn2 : ⌊x⌋₊ < 17 := (Nat.floor_lt hx0).mpr (by exact_mod_cast h2)\n"
               "  obtain ⟨-, -, h, -⟩ := h11_1 _ hn1 hn2 x (Nat.floor_le hx0) (Nat.lt_floor_add_one x)\n"
               "  have he : 0 ≤ ε₀ x := by\n"
               "    unfold Goals.Schoenfeld1976.epsilon0; positivity\n"
               "  have : 0 ≤ x * ε₀ x := mul_nonneg hx0 he\n"
               "  simp only [Nat.cast_zero, zero_div] at h\n"
               "  linarith\n")
    out.append("/-- Theorem 11, (7.2), on `[17, 1500)`. -/")
    out.append("theorem small_psi {x : ℝ} (h1 : 17 ≤ x) (h2 : x < 1500) :\n"
               "    |Chebyshev.psi x - x| < x * ε₀ x := by")
    out += cases(psi_blocks, 17, None)
    out.append("")
    out.append("/-- Theorem 11, (7.3), on `[101, 1500)`. -/")
    out.append("theorem small_theta {x : ℝ} (h1 : 101 ≤ x) (h2 : x < 1500) :\n"
               "    |Chebyshev.theta x - x| < x * ε₀ x := by")
    out += cases(theta_blocks, 101, None)
    out.append("")
    out.append("end TernaryGoldbach.RSBounds.SchoenfeldPrimeWalk")
    (ROOT / "RSBounds/SchoenfeldWalk11Data.lean").write_text('\n'.join(out) + '\n')
    print("wrote RSBounds/SchoenfeldWalk11Data.lean")


if __name__ == '__main__':
    main()
