"""Generate the segment, aggregator and final modules from tools/segments.json.

Layout:
  MoebiusCert/Large/LNNNN.lean  4 large-mode segments each (import only MoebiusCert.Defs)
  MoebiusCert/Small/SNNN.lean   8 per-element (M) segments each (import MoebiusCert.DefsSmall)
  MoebiusCert/Ms/MNNN.lean      8 (m) segments each (import MoebiusCert.DefsSmall)
  MoebiusCert/Agg/ALNN.lean     chains of large segments (import MoebiusCert.Segments + segment modules)
  MoebiusCert/Agg/Small.lean    chain of the small-mode (M) segments
  MoebiusCert/Agg/Ms.lean       chain of the (m) segments
  MoebiusCert/Final.lean        the two deliverable theorems
"""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
HDR = '''/-
Copyright (c) 2026 Harald Andrés Helfgott. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Harald Andrés Helfgott, Claude
-/
'''
d = json.load(open(os.path.join(ROOT, 'tools', 'segments.json')))

def I(x): return f"({x})" if x < 0 else str(x)

def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    old = open(full).read() if os.path.exists(full) else None
    if old != text:
        open(full, 'w').write(text)

def seg_modules(segs, per, folder, prefix, ns, imp, line):
    mods = []
    for m in range(0, len(segs), per):
        name = f"{prefix}{m // per:04d}" if prefix == 'L' else f"{prefix}{m // per:03d}"
        doc = ("/-! Large-mode segment checks (generated by tools/gen_modules.py). -/" if prefix == 'L' else
               "/-! Segment checks, generated by `tools/gen_modules.py`. Each is a kernel computation. -/")
        body = [(HDR if prefix != 'L' else "") + f"import {imp}", "", doc, "",
                f"namespace {ns}", "", "set_option maxRecDepth 100000", "set_option Elab.async false", ""]
        for s in segs[m:m + per]:
            body.append(line(s))
        body += ["", f"end {ns}", ""]
        write(f"MoebiusCert/{folder}/{name}.lean", "\n".join(body))
        mods.append((name, segs[m:m + per]))
    return mods

large = seg_modules(d['large_M'], 4, 'Large', 'L', 'MoebiusCert.Large', 'MoebiusCert.Defs',
    lambda s: f"theorem seg_{s[0]} : largeCheck {s[0]} {s[1]} {s[2]} {s[3]} {I(s[4])} {I(s[5])} = true := by decide +kernel")
small = seg_modules(d['small_M'], 8, 'Small', 'S', 'MoebiusCert.Small', 'MoebiusCert.DefsSmall',
    lambda s: f"theorem seg_{s[0]} : smallCheck {s[0]} {s[1]} {s[2]} {I(s[3])} {I(s[4])} = true := by decide +kernel")
ms = seg_modules(d['ms'], 8, 'Ms', 'M', 'MoebiusCert.Ms', 'MoebiusCert.DefsSmall',
    lambda s: f"theorem seg_{s[0]} : msCheck {s[0]} {s[1]} {s[2]} {I(s[3])} {I(s[4])} {s[5]} {I(s[6])} {I(s[7])} {s[8]} = true := by decide +kernel")

def chain(name, items, kind):
    """items: list of (L, S, a, b, proofterm) in order; kind 'Seg' or 'Ms'.
    Returns tactic proof lines and the resulting statement data."""
    lines = []
    L0 = items[0][0]
    T = items[0][1]
    lines.append(f"  have h0 := {items[0][4]}")
    for k, it in enumerate(items[1:], 1):
        T2 = T + it[1]
        lines.append(f"  have h{k} := {kind}Good.trans_eq (T := {T2}) h{k-1} ({it[4]}) (by norm_num) (by norm_num)")
        T = T2
    lines.append(f"  exact h{len(items) - 1}")
    return L0, T, lines

agg_mods = []
# large aggregators: 24 segment modules (96 segments) each
GROUP = 24
for g in range(0, len(large), GROUP):
    grp = large[g:g + GROUP]
    items = []
    for (mname, segs) in grp:
        for s in segs:
            L, K, lam, B, M0, Me = s
            items.append((L, 1 << K, M0, Me, f"largeCheck_sound _ _ _ _ _ _ MoebiusCert.Large.seg_{L}"))
    L0, T, lines = chain('x', items, 'Seg')
    aname = f"AL{g // GROUP:02d}"
    body = [HDR + "import MoebiusCert.Segments"] + [f"import MoebiusCert.Large.{m}" for (m, _) in grp] + ["",
            "/-! Chaining of large-mode segments, generated by `tools/gen_modules.py`. -/", "",
            "namespace MoebiusCert.Agg", "", "open MoebiusCert", "",
            f"theorem large_{g // GROUP:02d} : SegGood {L0} {T} {I(items[0][2])} {I(items[-1][3])} := by"] + lines + ["", "end MoebiusCert.Agg", ""]
    write(f"MoebiusCert/Agg/{aname}.lean", "\n".join(body))
    agg_mods.append((aname, f"large_{g // GROUP:02d}", L0, T, items[0][2], items[-1][3]))

# small (M) chain
items = []
for (mname, segs) in small:
    for s in segs:
        L, K, lam, M0, Me = s
        items.append((L, 1 << K, M0, Me, f"smallCheck_sound _ _ _ _ _ MoebiusCert.Small.seg_{L}"))
L0, T, lines = chain('x', items, 'Seg')
body = [HDR + "import MoebiusCert.SmallSeg"] + [f"import MoebiusCert.Small.{m}" for (m, _) in small] + ["",
        "/-! Chaining of the per-element `(M)` segments, generated by `tools/gen_modules.py`. -/", "",
        "namespace MoebiusCert.Agg", "", "open MoebiusCert", "",
        f"theorem small : SegGood {L0} {T} {I(items[0][2])} {I(items[-1][3])} := by"] + lines + ["", "end MoebiusCert.Agg", ""]
write("MoebiusCert/Agg/Small.lean", "\n".join(body))
small_agg = (L0, T, items[0][2], items[-1][3])

# (m) chain
items = []
for (mname, segs) in ms:
    for s in segs:
        L, K, lam, lo0, hi0, e0, lo1, hi1, e1 = s
        items.append((L, 1 << K, (lo0, hi0), (lo1, hi1), f"msCheck_sound _ _ _ _ _ _ _ _ _ MoebiusCert.Ms.seg_{L}"))
L0, T, lines = chain('x', items, 'Ms')
a0, a1 = items[0][2], items[-1][3]
body = [HDR + "import MoebiusCert.MsSeg"] + [f"import MoebiusCert.Ms.{m}" for (m, _) in ms] + ["",
        "/-! Chaining of the `(m)` segments, generated by `tools/gen_modules.py`. -/", "",
        "namespace MoebiusCert.Agg", "", "open MoebiusCert", "",
        f"theorem msAll : MsGood {L0} {T} {I(a0[0])} {I(a0[1])} {I(a1[0])} {I(a1[1])} := by"] + lines + ["", "end MoebiusCert.Agg", ""]
write("MoebiusCert/Agg/Ms.lean", "\n".join(body))
ms_agg = (L0, T)

# final chain of (M)
chain_items = [(small_agg[0], small_agg[1], small_agg[2], small_agg[3], "MoebiusCert.Agg.small")]
for (aname, tname, L0_, T_, a_, b_) in agg_mods:
    chain_items.append((L0_, T_, a_, b_, f"MoebiusCert.Agg.{tname}"))
L0, T, lines = chain('x', chain_items, 'Seg')
assert L0 == 1 and L0 + T - 1 >= 10 ** 9, (L0, T)
assert ms_agg[0] == 1 and ms_agg[1] >= 600001
final = [HDR + "import RSBounds.MoebiusInputs", "import MoebiusCert.Agg.Small", "import MoebiusCert.Agg.Ms"] + \
        [f"import MoebiusCert.Agg.{a[0]}" for a in agg_mods] + ["",
"""/-!
# The two Möbius computations

`mertensSqrt` and `smallMoebiusSum`, the hypotheses (M) and (m) of `mobius003.tex`, from the
kernel-checked segment computations.
-/

namespace MoebiusCert

/-- The whole range `[1, 1000013823]` for `(M)`. -/""",
f"theorem mertens_all : SegGood 1 {T} 0 {I(chain_items[-1][3])} := by"] + lines + ["""
end MoebiusCert

namespace TernaryGoldbach.RSBounds.MoebiusInputs

open MoebiusCert

theorem mertensSqrt : MertensSqrt := by
  intro n hn1 hn2
  obtain ⟨hb, -⟩ := mertens_all (by simp [mert_zero])
  exact hb n (by omega) (by omega) hn1

theorem smallMoebiusSum : SmallMoebiusSum := by
  intro n hn1 hn2
  obtain ⟨hb, -⟩ := MoebiusCert.Agg.msAll (by simp [MsInv, msum])
  exact hb n (by omega) (by omega) hn1

end TernaryGoldbach.RSBounds.MoebiusInputs
"""]
write("MoebiusCert/Final.lean", "\n".join(final))
write("MoebiusCert.lean", HDR + "import MoebiusCert.Final\n")
print("large modules", len(large), "small", len(small), "ms", len(ms), "aggregators", len(agg_mods))
