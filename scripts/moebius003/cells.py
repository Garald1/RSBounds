"""Generator of the cell data for RSBounds/Moebius003/CellData.lean.

Mirrors the Lean checker `checkCells` (Checker.lean) in floating point, chooses y per cell to
minimise nu, and rounds nu and eta up by a relative 1e-7 to multiples of 1e-12. The exact check is
done by the Lean kernel; this script only proposes the data.
"""
import math, json, re
from fractions import Fraction as F

# ghTable from LambdaInputs.lean
src = open("../RSBounds/LambdaInputs.lean").read()
rows = re.findall(r"⟨(\d+), (\d+), (\d+), (\d+), (\d+)⟩", src)
GH = {int(r[0]): tuple(int(x) for x in r[1:]) for r in rows}
GH[1] = (0, 0, 0, 0)
assert len(GH) == 46

X0 = 10**9; Vn = 10**10; C5 = 0.0077629; cM = 0.571
kLo, kHi = 0.6079267, 0.6079274
eLo, eHi = 0.96, 1.17
C0B, I0B = 1743.0, 36113.0
logV = math.log(1e10)
Dmid = 942467 * 10**53
Dend = 306985 * 10**64

E = json.load(open("endpoints.json"))
D = [int(x) for x in E["D"]]
assert D[0] == X0 and D[-1] == Dend and int(E["Dmid"]) == Dmid

def logf(x):  # float log of a big int
    return math.log(x) if x < 1e300 else math.log(x / 10**200) + 200 * math.log(10)

def etaMax(prev, lo, hi):
    v = [e for (a, b, e) in prev if a <= hi and lo < b]
    return max(v) if v else 0.0

def blocks_for(y):
    bs = []; s = 1
    while 2**s < y: bs.append(2**s); s += 1
    bs.append(y)
    return bs

def cellK(prev, Dlo, Dhi, y, bs, sD, sy):
    K = 0.0; al = 1
    for be in bs:
        glA, _, hlA, _ = GH[al]; _, ghB, _, hhB = GH[be]
        lo = Dlo // be; hi = (Dhi - 1) // max(al + 1, 2)
        w = 0.0
        if lo <= X0: w += cM * ((hhB - hlA) / 1e6) / sD
        if X0 < hi: w += etaMax(prev, max(lo, X0 + 1), hi) * ((ghB - glA) / 1e6)
        K += w; al = be
    lo = Dlo // y; hi = (Dhi - 1) // y
    r = 0.0
    if lo <= X0: r += 0.8 * cM / sD
    if X0 < hi: r += 0.8 * etaMax(prev, max(lo, X0 + 1), hi) / sy
    return K + r

def jW(Dlo, Dhi, y, sD, sy, Lm, Lp):
    J = 0.0
    if Vn < Dhi:
        J += C5 * (kHi * (math.log(Lp / logV) + 2 / logV**2) + (eHi - eLo) / logV + eLo / Lm)
    J += 1.6 * kHi / sy + 0.8 * (4 - kLo + logf(Dhi) - math.log(y)) / sD + kHi / y + 2 / (sD * sy) + 1 / Dlo
    return J

def up(x, slack=1e-7, den=10**12):
    return F(math.ceil(x * (1 + slack) * den), den)

table = sorted(GH)
prev = []; I = 0.0; T = 0.0; out = []
stats = []
for i in range(len(D) - 1):
    Dlo, Dhi = D[i], D[i + 1]
    Lm, Lp = logf(Dlo), logf(Dhi)
    sD = math.sqrt(Dlo)
    dl = 1 - Dlo / Dhi
    best = None
    for y in table:
        if not (1500 <= y <= 2**20 and 33 * y <= Dlo): continue
        sy = math.sqrt(y); bs = blocks_for(y)
        K = cellK(prev, Dlo, Dhi, y, bs, sD, sy)
        J = jW(Dlo, Dhi, y, sD, sy, Lm, Lp)
        X = 1 / Dlo + K + J
        nu = (X + (C0B + I) / Dlo) / (1 - 1 / Lm - dl / Lm**2)
        if best is None or nu < best[0]: best = (nu, y, bs, K, J)
    nu, y, bs, K, J = best
    nuq = up(nu)
    eta = float(nuq) / Lm + (C0B + I) / Dlo + float(nuq) * dl / Lm**2
    etaq = up(eta)
    e = float(etaq)
    m = Lp * (e + max((I0B + T) / Dlo, (I0B + T + e * (Dhi - Dlo)) / Dhi) + Lp / Dlo)
    assert m <= 0.03 * (1 - 1e-6), (i, m)
    assert float(nuq) <= 0.017
    assert Dhi <= Dmid or float(nuq) <= 0.014, i
    out.append(dict(Dlo=Dlo, Dhi=Dhi, y=y, bs=bs, nu=nuq, eta=etaq))
    stats.append((i + 1, Lm, Lp, y, K, J, float(nuq), e * Lm, m))
    prev.append((Dlo, Dhi, e))
    I = I + float(nuq) * (Dhi - Dlo) / Lm**2
    T = T + e * (Dhi - Dlo)

print("cells", len(out), "max nu %.6f" % max(s[6] for s in stats), "max m %.6f at %d" % max((s[8], s[0]) for s in stats))
print("max nu (Dhi > Dmid) %.6f" % max(s[6] for s, c in zip(stats, out) if c["Dhi"] > Dmid))
json.dump(stats, open("cells_stats.json", "w"))
with open("cells.csv", "w") as f:
    f.write("i,logDlo,logDhi,y,K,J,nu,etaL,m\n")
    for s in stats: f.write("%d,%.6f,%.6f,%d,%.6f,%.6f,%.6f,%.6f,%.6f\n" % s)

# Lean output
